export const FORMATS = {
    json: { label: "JSON", ext: "json", mime: "application/json" },
    array: { label: "Array", ext: "json", mime: "application/json" },
    netscape: { label: "Netscape", ext: "txt", mime: "text/plain" },
    header: { label: "Header", ext: "txt", mime: "text/plain" },
};

export function encode(format, cookies, meta = {}) {
    switch (format) {
        case "json":
            return encodeJsonWrapped(cookies, meta);
        case "array":
            return encodeJsonArray(cookies, meta);
        case "netscape":
            return encodeNetscape(cookies);
        case "header":
            return encodeHeader(cookies);
        default:
            throw new Error(`Unknown export format: ${format}`);
    }
}

/** Auto-detects format from raw file content and returns cookie objects. */
export function decode(text) {
    const trimmed = text.trimStart();
    if (trimmed.startsWith("{")) return { format: "json", cookies: decodeJsonWrapped(trimmed) };
    if (trimmed.startsWith("[")) return { format: "array", cookies: decodeJsonArray(trimmed) };
    if (trimmed.startsWith("# Netscape") || trimmed.includes("\t")) {
        return { format: "netscape", cookies: decodeNetscape(text) };
    }
    if (trimmed.includes("=")) return { format: "header", cookies: decodeHeader(trimmed) };
    throw new Error("Unrecognized file format.");
}

function encodeJsonWrapped(cookies, { source, scope, pretty }) {
    const payload = {
        exportedAt: new Date().toISOString(),
        source: source ?? null,
        scope,
        count: cookies.length,
        cookies,
    };
    return JSON.stringify(payload, null, pretty ? 2 : 0);
}

function encodeJsonArray(cookies, { pretty }) {
    return JSON.stringify(cookies, null, pretty ? 2 : 0);
}

function encodeNetscape(cookies) {
    const header =
        "# Netscape HTTP Cookie File\n" +
        "# https://curl.se/docs/http-cookies.html\n" +
        "# Generated by Cookies Kitchen — do not edit.\n\n";
    const lines = cookies.map((c) => {
        const domain = c.domain || "";
        const includeSubdomains = domain.startsWith(".") ? "TRUE" : "FALSE";
        const path = c.path || "/";
        const secure = c.secure ? "TRUE" : "FALSE";
        const expiration = c.session ? "0" : Math.floor(c.expirationDate || 0);
        const prefix = c.httpOnly ? "#HttpOnly_" : "";
        return `${prefix}${domain}\t${includeSubdomains}\t${path}\t${secure}\t${expiration}\t${c.name}\t${c.value}`;
    });
    return header + lines.join("\n") + "\n";
}

function encodeHeader(cookies) {
    return cookies.map((c) => `${c.name}=${c.value}`).join("; ");
}

function decodeJsonWrapped(text) {
    const data = JSON.parse(text);
    const cookies = Array.isArray(data) ? data : data.cookies;
    if (!Array.isArray(cookies)) {
        throw new Error("JSON object missing 'cookies' array.");
    }
    return cookies;
}

function decodeJsonArray(text) {
    const data = JSON.parse(text);
    if (!Array.isArray(data)) {
        throw new Error("Expected a JSON array of cookies.");
    }
    return data;
}

function decodeNetscape(text) {
    const cookies = [];
    for (const rawLine of text.split(/\r?\n/)) {
        let line = rawLine;
        let httpOnly = false;
        if (line.startsWith("#HttpOnly_")) {
            line = line.slice("#HttpOnly_".length);
            httpOnly = true;
        }
        if (!line || line.startsWith("#")) continue;
        const parts = line.split("\t");
        if (parts.length < 7) continue;
        const [domain, , path, secure, expiration, name, ...valueParts] = parts;
        const value = valueParts.join("\t");
        const exp = parseInt(expiration, 10);
        const cookie = {
            domain,
            path: path || "/",
            secure: secure === "TRUE",
            httpOnly,
            name,
            value,
            sameSite: "unspecified",
        };
        if (Number.isFinite(exp) && exp > 0) {
            cookie.expirationDate = exp;
        } else {
            cookie.session = true;
        }
        cookies.push(cookie);
    }
    return cookies;
}

function decodeHeader(text) {
    return text
        .split(/;\s*/)
        .map((pair) => pair.trim())
        .filter(Boolean)
        .map((pair) => {
            const idx = pair.indexOf("=");
            if (idx < 0) return null;
            return {
                name: pair.slice(0, idx).trim(),
                value: pair.slice(idx + 1).trim(),
            };
        })
        .filter(Boolean);
}
